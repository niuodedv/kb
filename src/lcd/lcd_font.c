/*
 * LCD 5x7 ASCII 子集字体实现（按需收录）
 * 详见 lcd_font.h
 *
 * 位约定：每个字形行字节的 bit0=最左列、bit4=最右列，
 * 与 lcd.c 中 glyph_row() 的 (bits & (1u<<col)) 画到 x=col 一致，
 * 修改字形时务必先画出 5 列像素再填位，勿横向翻转。
 */

#include "lcd_font.h"

#include <stddef.h>

/* 查表用字符序列：顺序必须与 FONT_GLYPHS 一一对应 */
static const char font_chars[] = " 0123456789:-.%USBEGLCH";

static const uint8_t font_glyphs[][KB_FONT_H] = {
	/* ' ' */ { 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00 },
	/* '0' */ { 0x0E, 0x11, 0x19, 0x15, 0x13, 0x11, 0x0E },
	/* '1' */ { 0x04, 0x06, 0x04, 0x04, 0x04, 0x0E, 0x0E },
	/* '2' */ { 0x0E, 0x11, 0x10, 0x08, 0x04, 0x02, 0x1F },
	/* '3' */ { 0x0E, 0x11, 0x10, 0x0C, 0x10, 0x11, 0x0E },
	/* '4' */ { 0x08, 0x0C, 0x0A, 0x09, 0x1F, 0x10, 0x10 },
	/* '5' */ { 0x1F, 0x01, 0x0F, 0x10, 0x10, 0x11, 0x0E },
	/* '6' */ { 0x0E, 0x01, 0x01, 0x0F, 0x11, 0x11, 0x0E },
	/* '7' */ { 0x1F, 0x10, 0x08, 0x04, 0x02, 0x02, 0x02 },
	/* '8' */ { 0x0E, 0x11, 0x11, 0x0E, 0x11, 0x11, 0x0E },
	/* '9' */ { 0x0E, 0x11, 0x11, 0x0F, 0x10, 0x11, 0x0E },
	/* ':' */ { 0x00, 0x04, 0x04, 0x00, 0x00, 0x04, 0x04 },
	/* '-' */ { 0x00, 0x00, 0x00, 0x0E, 0x00, 0x00, 0x00 },
	/* '.' */ { 0x00, 0x00, 0x00, 0x00, 0x00, 0x04, 0x00 },
	/* '%' */ { 0x03, 0x13, 0x0B, 0x04, 0x1A, 0x19, 0x18 },
	/* 'U' */ { 0x11, 0x11, 0x11, 0x11, 0x11, 0x11, 0x0E },
	/* 'S' */ { 0x0E, 0x11, 0x01, 0x0E, 0x10, 0x11, 0x0E },
	/* 'B' */ { 0x0F, 0x11, 0x11, 0x0F, 0x11, 0x11, 0x0F },
	/* 'E' */ { 0x1F, 0x01, 0x01, 0x0F, 0x01, 0x01, 0x1F },
	/* 'G' */ { 0x0E, 0x11, 0x01, 0x1D, 0x11, 0x11, 0x0E },
	/* 'L' */ { 0x01, 0x01, 0x01, 0x01, 0x01, 0x01, 0x1F },
	/* 'C' */ { 0x0E, 0x11, 0x01, 0x01, 0x01, 0x11, 0x0E },
	/* 'H' */ { 0x11, 0x11, 0x11, 0x1F, 0x11, 0x11, 0x11 },
};

const uint8_t *kb_lcd_font_glyph(char ch)
{
	for (size_t i = 0; font_chars[i] != '\0'; i++) {
		if (font_chars[i] == ch) {
			return font_glyphs[i];
		}
	}

	return NULL;
}
